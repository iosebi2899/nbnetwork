export function placeFaq(p: Place): FaqItem[] {
  const loc = locative(p.name);
  const m = municipality(p.municipality);
  const where = [p.community, m.full].filter(Boolean).join(', ');
  return [
    {
      q: `შეგიძლიათ ინტერნეტის შემოყვანა ${loc}?`,
      a: isConfirmed(p)
        ? `დიახ. ${p.name} (${where}) ჩვენი დაფარვის ზონაშია. დაგვირეკეთ ${SITE.phoneDisplay} და ინტერნეტს მოკლე დროში შემოგიყვანთ.`
        : `${p.name} მდებარეობს ${m.loc} (${where}), სადაც ჩვენი ქსელი ფართოვდება. დაგვირეკეთ ${SITE.phoneDisplay} — გადავამოწმებთ, შესაძლებელია თუ არა ინტერნეტის შემოყვანა თქვენს მისამართზე.`,
    },
    {
      q: `რა ღირს ინტერნეტი ${loc}?`,
      a: `ინტერნეტ პაკეტები ${loc}: ${priceList} თვეში.`,
    },
    {
      q: 'როგორ გადავიხადო ინტერნეტის საფასური?',
      a: payment,
    },
  ];
}
